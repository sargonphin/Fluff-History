using System.Text;
using System.Text.Json;
using System.Xml.Linq;

namespace FluffHistory.Localization;

internal static class LiveXamlResources
{
    internal const string GeneratedPath = "src/FluffHistory.Desktop/Presentation/Localize.Bindings.g.cs";
    internal static void Generate(string root, IReadOnlyDictionary<string, string> catalog, bool check)
    {
        XNamespace loc = "using:FluffHistory.Desktop.Presentation";
        var elements = PresentationGuard.SourceFiles(Path.Combine(root, "src/FluffHistory.Desktop"), "*.xaml")
            .SelectMany(file => XDocument.Load(file).Descendants()).Where(e => e.Attribute(loc + "Localize.Uid") is not null)
            .GroupBy(e => (string)e.Attribute(loc + "Localize.Uid")!).OrderBy(g => g.Key, StringComparer.Ordinal);
        var output = new StringBuilder("// Generated by tools/FluffHistory.Localization; edit XAML and canonical RESW.\nnamespace FluffHistory.Desktop.Presentation;\n\npublic static partial class Localize\n{\n    private static void BindResources(global::Microsoft.UI.Xaml.DependencyObject target, string uid)\n    {\n        switch (uid)\n        {\n");
        var count = 0;
        foreach (var group in elements)
        {
            var types = group.Select(e => e.Name.LocalName).Distinct().ToArray();
            if (types.Length != 1) throw new InvalidDataException("A live resource ID must have one control type: " + group.Key);
            var keys = catalog.Keys.Where(k => k.StartsWith(group.Key + ".", StringComparison.Ordinal)).Order(StringComparer.Ordinal).ToArray();
            if (keys.Length == 0) throw new InvalidDataException("Unknown live resource ID: " + group.Key);
            output.Append("            case ").Append(JsonSerializer.Serialize(group.Key)).Append(":\n");
            foreach (var key in keys)
            {
                var property = key[(group.Key.Length + 1)..];
                // MakePRI turns property separators into map subtrees, preserving
                // dots inside the [using:...] namespace qualifier.
                var separator = property.LastIndexOf('.');
                var resource = group.Key + "/" + (separator < 0 ? property :
                    property[..separator] + "/" + property[(separator + 1)..]);
                string owner;
                if (property.StartsWith("[using:", StringComparison.Ordinal))
                {
                    var end = property.IndexOf(']');
                    owner = "global::" + property[7..end] + "." + property[(end + 1)..property.LastIndexOf('.')];
                    property = property[(property.LastIndexOf('.') + 1)..];
                }
                else owner = "global::Microsoft.UI.Xaml.Controls." + types[0];
                output.Append("                Bind(target, ").Append(owner).Append('.').Append(property)
                    .Append("Property, ").Append(JsonSerializer.Serialize(resource)).Append(");\n");
                count++;
            }
            output.Append("                break;\n");
        }
        output.Append("            default: throw new global::System.InvalidOperationException(\"Unknown live resource identifier.\");\n        }\n    }\n}\n");
        var path = Path.Combine(root, GeneratedPath);
        if (check)
        {
            if (!File.Exists(path) || File.ReadAllText(path).Replace("\r\n", "\n") != output.ToString())
                throw new InvalidDataException("Generated live XAML bindings are stale. Run generate.");
        }
        else File.WriteAllText(path, output.ToString());
        Console.WriteLine($"Live XAML resource bindings {(check ? "current" : "generated")}: {count} properties.");
    }
}
